use super::Family;

#[derive(Clone, Copy)]
pub(super) enum RootBase {
    XdgConfig,
    ChromeConfigHome,
    ChromeUserData,
    Home,
}

#[derive(Clone, Copy)]
pub(super) struct RootSpec {
    pub(super) browser_id: &'static str,
    pub(super) browser_label: &'static str,
    pub(super) family: Family,
    pub(super) base: RootBase,
    pub(super) rel_path: &'static str,
    pub(super) flat_root: bool,
}

impl RootSpec {
    const fn new(
        browser_id: &'static str,
        browser_label: &'static str,
        family: Family,
        base: RootBase,
        rel_path: &'static str,
        flat_root: bool,
    ) -> Self {
        Self {
            browser_id,
            browser_label,
            family,
            base,
            rel_path,
            flat_root,
        }
    }
}

